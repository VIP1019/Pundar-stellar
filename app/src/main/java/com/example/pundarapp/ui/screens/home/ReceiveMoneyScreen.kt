@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun ReceiveMoneyScreen(navController: NavController) {
    val context = LocalContext.current
    val user by AuthRepository.currentUserState

    LaunchedEffect(Unit) {
        AppState.fetchExchangeRate()
    }

    // Comprehensive Pre-QR configuration state
    var requestMode by remember { mutableIntStateOf(0) } // 0 = Group Split / Join Pay, 1 = Direct Payment Request
    var billTitleInput by remember { mutableStateOf("") }
    var selectedCategory by remember { mutableStateOf("Food & Dining") }
    var amountInput by remember { mutableStateOf("") }
    var peopleCountInput by remember { mutableStateOf("2") }
    var notesInput by remember { mutableStateOf("") }
    var isQrGenerated by remember { mutableStateOf(false) }

    var showGenerateConfirmDialog by remember { mutableStateOf(false) }
    var statusDialogState by remember { mutableStateOf<Triple<String, String, Boolean>?>(null) }

    val categories = remember {
        listOf("Food & Dining", "Utilities", "Rent", "Travel", "Groceries", "General")
    }
    val quickAmounts = remember {
        listOf("100", "250", "500", "1000", "2500")
    }

    var qrMode by remember { mutableIntStateOf(0) } // 0 = PUNDAR QR, 1 = Stellar SEP-0007 QR
    var refreshNonce by remember { mutableIntStateOf(0) }

    val totalAmount = amountInput.toDoubleOrNull()?.takeIf { it > 0.0 }
    val effectivePeopleCountStr = if (requestMode == 1) "1" else peopleCountInput
    val peopleCount = effectivePeopleCountStr.toIntOrNull()?.takeIf { it >= 1 }
    val isTitleValid = billTitleInput.trim().isNotEmpty()
    val isFormValid = totalAmount != null && peopleCount != null && isTitleValid

    // Exact fixed amount each participant pays when scanning the QR code
    val perPersonAmount: Double? = if (totalAmount != null && peopleCount != null) {
        totalAmount / peopleCount
    } else {
        null
    }

    val effectiveBillTitle = remember(billTitleInput, selectedCategory, notesInput, peopleCount) {
        val baseTitle = billTitleInput.trim().ifBlank {
            if ((peopleCount ?: 1) > 1) "Split Bill (${peopleCount ?: 2} people)" else "Payment Request"
        }
        val withCat = "[$selectedCategory] $baseTitle"
        if (notesInput.trim().isNotEmpty()) "$withCat - ${notesInput.trim()}" else withCat
    }

    val qrContent: String? = remember(
        user?.id,
        user?.stellarPublicKey,
        perPersonAmount,
        totalAmount,
        peopleCount,
        effectiveBillTitle,
        qrMode,
        refreshNonce,
        isQrGenerated
    ) {
        if (!isQrGenerated) return@remember null
        val currentUser = user ?: return@remember null
        val fixedShare = perPersonAmount ?: return@remember null
        val total = totalAmount ?: return@remember null
        val count = peopleCount ?: return@remember null

        if (qrMode == 1 && !currentUser.stellarPublicKey.isNullOrBlank()) {
            val shareXlm = AppState.phpToXlm(fixedShare)
            val formattedShareXlm = String.format(Locale.US, "%.7f", shareXlm)
            val formattedSharePhp = String.format(Locale.US, "%.2f", fixedShare)
            val formattedTotal = String.format(Locale.US, "%.2f", total)
            "web+stellar:pay?destination=${currentUser.stellarPublicKey}&amount=$formattedShareXlm&amountPhp=$formattedSharePhp&totalAmount=$formattedTotal&participants=$count&memo=${java.net.URLEncoder.encode(effectiveBillTitle, "UTF-8")}"
        } else {
            val payload = QrCodeGenerator.createReceiveMoneyPayload(
                userId = currentUser.id,
                displayName = currentUser.name,
                username = currentUser.phone,
                walletId = currentUser.stellarPublicKey,
                amount = fixedShare,
                totalBillAmount = total,
                participantCount = count,
                billRef = effectiveBillTitle
            )
            QrPayload.encode(payload)
        }
    }

    val qrBitmap: Bitmap? = remember(qrContent) {
        qrContent?.let {
            try {
                QrCodeGenerator.generateBitmap(it, 512)
            } catch (_: Exception) {
                null
            }
        }
    }

    if (showGenerateConfirmDialog && totalAmount != null && peopleCount != null && perPersonAmount != null) {
        PundarConfirmDialog(
            title = "Confirm QR Request Setup",
            message = "Please review the payment details below. Once generated, anyone scanning this QR code will have their payment amount locked.",
            confirmText = "Generate QR",
            dismissText = "Edit Info",
            icon = Icons.Filled.QrCode,
            details = buildList {
                add("Request Type" to if (requestMode == 0) "Group Split / Join Pay" else "Direct Payment")
                add("Title" to billTitleInput.trim())
                add("Category" to selectedCategory)
                add("Total Amount" to "₱${String.format(Locale.US, "%,.2f", totalAmount)}")
                add("Participants" to "$peopleCount ${if (peopleCount == 1) "person" else "people"}")
                add("Locked Share / Person" to "₱${String.format(Locale.US, "%,.2f", perPersonAmount)}")
                if (notesInput.trim().isNotEmpty()) {
                    add("Notes" to notesInput.trim())
                }
            },
            onConfirm = {
                showGenerateConfirmDialog = false
                isQrGenerated = true
            },
            onDismiss = { showGenerateConfirmDialog = false }
        )
    }

    statusDialogState?.let { (title, msg, isErr) ->
        PundarStatusDialog(
            title = title,
            message = msg,
            isError = isErr,
            onDismiss = { statusDialogState = null }
        )
    }

    Scaffold(
        topBar = {
            PundarDetailTopBar(
                title = if (isQrGenerated) "Receive Money QR" else "Configure QR Request",
                onBack = {
                    if (isQrGenerated) {
                        isQrGenerated = false
                    } else {
                        navController.navigateUp()
                    }
                }
            )
        },
        containerColor = PundarTheme.colors.bgPrimary
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .verticalScroll(rememberScrollState())
                .padding(16.dp),
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = Arrangement.spacedBy(14.dp)
        ) {
            val displayName = user?.name ?: "User"
            val initials = AuthRepository.getCurrentUserInitials()

            PundarAvatar(
                initials = initials,
                imageUrl = user?.profileImageUrl,
                size = 64.dp,
                showRing = true,
                initialsFontSize = 22.sp
            )

            Text(
                displayName,
                style = MaterialTheme.typography.titleLarge,
                fontWeight = FontWeight.Bold,
                color = PundarTheme.colors.textPrimary
            )
            Text(
                user?.phone ?: "",
                style = MaterialTheme.typography.bodyMedium,
                color = PundarTheme.colors.textSecondary
            )

            if (!isQrGenerated) {
                // ── STEP 1: COMPREHENSIVE INFO SETUP BEFORE QR IS GENERATED ──
                Card(
                    modifier = Modifier.fillMaxWidth(),
                    colors = CardDefaults.cardColors(containerColor = PundarTheme.colors.surfacePrimary),
                    shape = RoundedCornerShape(20.dp),
                    border = BorderStroke(1.dp, PundarTheme.colors.borderPrimary)
                ) {
                    Column(
                        modifier = Modifier.padding(20.dp).fillMaxWidth(),
                        verticalArrangement = Arrangement.spacedBy(16.dp)
                    ) {
                        Row(verticalAlignment = Alignment.CenterVertically) {
                            Box(
                                modifier = Modifier
                                    .size(42.dp)
                                    .clip(RoundedCornerShape(12.dp))
                                    .background(PundarTheme.colors.brandPrimary.copy(alpha = 0.12f)),
                                contentAlignment = Alignment.Center
                            ) {
                                Icon(
                                    Icons.Filled.Groups,
                                    contentDescription = null,
                                    tint = PundarTheme.colors.brandPrimary
                                )
                            }
                            Spacer(Modifier.width(12.dp))
                            Column {
                                Text(
                                    "Configure Payment Request",
                                    style = MaterialTheme.typography.titleMedium,
                                    fontWeight = FontWeight.Bold,
                                    color = PundarTheme.colors.textPrimary
                                )
                                Text(
                                    "Fill in the request type, title, category, amount, and participants before generating the QR code.",
                                    style = MaterialTheme.typography.bodySmall,
                                    color = PundarTheme.colors.textSecondary
                                )
                            }
                        }

                        // 1. Request Type Mode Selector
                        Text(
                            "1. Request Type *",
                            style = MaterialTheme.typography.labelLarge,
                            fontWeight = FontWeight.SemiBold,
                            color = PundarTheme.colors.textPrimary
                        )
                        SingleChoiceSegmentedButtonRow(modifier = Modifier.fillMaxWidth()) {
                            SegmentedButton(
                                selected = requestMode == 0,
                                onClick = {
                                    requestMode = 0
                                    if (peopleCountInput == "1") peopleCountInput = "2"
                                },
                                shape = SegmentedButtonDefaults.itemShape(index = 0, count = 2)
                            ) { Text("Split / Join Pay", fontSize = 12.sp) }
                            SegmentedButton(
                                selected = requestMode == 1,
                                onClick = {
                                    requestMode = 1
                                    peopleCountInput = "1"
                                },
                                shape = SegmentedButtonDefaults.itemShape(index = 1, count = 2)
                            ) { Text("Single Payment", fontSize = 12.sp) }
                        }

                        // 2. Bill / Request Purpose Title (Required)
                        Text(
                            "2. Bill / Request Title *",
                            style = MaterialTheme.typography.labelLarge,
                            fontWeight = FontWeight.SemiBold,
                            color = PundarTheme.colors.textPrimary
                        )
                        OutlinedTextField(
                            value = billTitleInput,
                            onValueChange = { billTitleInput = it },
                            label = { Text("Bill or Payment Purpose *") },
                            placeholder = { Text("e.g. Team Dinner, Monthly Wi-Fi, Coffee Run") },
                            singleLine = true,
                            modifier = Modifier.fillMaxWidth(),
                            shape = RoundedCornerShape(12.dp),
                            colors = OutlinedTextFieldDefaults.colors(
                                focusedBorderColor = PundarTheme.colors.brandPrimary,
                                focusedLabelColor = PundarTheme.colors.brandPrimary,
                                focusedTextColor = PundarTheme.colors.textPrimary,
                                unfocusedTextColor = PundarTheme.colors.textPrimary
                            ),
                            supportingText = {
                                if (!isTitleValid) {
                                    Text(
                                        "Required: Enter a title or purpose for this QR request.",
                                        color = MaterialTheme.colorScheme.error,
                                        style = MaterialTheme.typography.bodySmall
                                    )
                                }
                            }
                        )

                        // 3. Category Selector Chips
                        Text(
                            "3. Expense / Request Category *",
                            style = MaterialTheme.typography.labelLarge,
                            fontWeight = FontWeight.SemiBold,
                            color = PundarTheme.colors.textPrimary
                        )
                        Row(
                            modifier = Modifier
                                .fillMaxWidth()
                                .horizontalScroll(rememberScrollState()),
                            horizontalArrangement = Arrangement.spacedBy(8.dp)
                        ) {
                            categories.forEach { cat ->
                                val selected = selectedCategory == cat
                                FilterChip(
                                    selected = selected,
                                    onClick = { selectedCategory = cat },
                                    label = { Text(cat, fontSize = 12.sp) },
                                    leadingIcon = if (selected) {
                                        { Icon(Icons.Filled.Category, contentDescription = null, modifier = Modifier.size(14.dp)) }
                                    } else null
                                )
                            }
                        }

                        // 4. Total Bill / Request Amount (Required)
                        Text(
                            "4. Total Amount to Settle (₱) *",
                            style = MaterialTheme.typography.labelLarge,
                            fontWeight = FontWeight.SemiBold,
                            color = PundarTheme.colors.textPrimary
                        )
                        OutlinedTextField(
                            value = amountInput,
                            onValueChange = { input ->
                                if (input.isEmpty() || input.matches(Regex("^\\d*\\.?\\d{0,2}$"))) {
                                    amountInput = input
                                }
                            },
                            label = { Text("Total Bill / Request Amount (₱) *") },
                            placeholder = { Text("e.g. 1000.00") },
                            singleLine = true,
                            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Decimal),
                            modifier = Modifier.fillMaxWidth(),
                            shape = RoundedCornerShape(12.dp),
                            colors = OutlinedTextFieldDefaults.colors(
                                focusedBorderColor = PundarTheme.colors.brandPrimary,
                                focusedLabelColor = PundarTheme.colors.brandPrimary,
                                focusedTextColor = PundarTheme.colors.textPrimary,
                                unfocusedTextColor = PundarTheme.colors.textPrimary
                            ),
                            supportingText = {
                                if (totalAmount == null) {
                                    Text(
                                        "Required: Enter the amount to request.",
                                        color = MaterialTheme.colorScheme.error,
                                        style = MaterialTheme.typography.bodySmall
                                    )
                                }
                            }
                        )

                        // Quick Amount Preset Chips
                        Row(
                            modifier = Modifier.fillMaxWidth(),
                            horizontalArrangement = Arrangement.spacedBy(6.dp)
                        ) {
                            quickAmounts.forEach { preset ->
                                val isPresetSelected = amountInput == preset
                                OutlinedButton(
                                    onClick = { amountInput = preset },
                                    modifier = Modifier.weight(1f),
                                    shape = RoundedCornerShape(10.dp),
                                    contentPadding = PaddingValues(vertical = 6.dp),
                                    border = BorderStroke(
                                        1.dp,
                                        if (isPresetSelected) PundarTheme.colors.brandPrimary else PundarTheme.colors.borderPrimary
                                    ),
                                    colors = ButtonDefaults.outlinedButtonColors(
                                        containerColor = if (isPresetSelected) PundarTheme.colors.brandPrimary.copy(alpha = 0.12f) else PundarTheme.colors.surfacePrimary
                                    )
                                ) {
                                    Text(
                                        text = "₱$preset",
                                        fontSize = 11.sp,
                                        fontWeight = if (isPresetSelected) FontWeight.Bold else FontWeight.Medium,
                                        color = if (isPresetSelected) PundarTheme.colors.brandPrimary else PundarTheme.colors.textPrimary
                                    )
                                }
                            }
                        }

                        // 5. Quantity of People Joining the Bill (Shown for Split mode)
                        if (requestMode == 0) {
                            Text(
                                "5. Quantity of People Joining the Bill *",
                                style = MaterialTheme.typography.labelLarge,
                                fontWeight = FontWeight.SemiBold,
                                color = PundarTheme.colors.textPrimary
                            )

                            Row(
                                modifier = Modifier.fillMaxWidth(),
                                verticalAlignment = Alignment.CenterVertically,
                                horizontalArrangement = Arrangement.spacedBy(12.dp)
                            ) {
                                IconButton(
                                    onClick = {
                                        val current = peopleCountInput.toIntOrNull() ?: 1
                                        if (current > 1) peopleCountInput = (current - 1).toString()
                                    },
                                    modifier = Modifier
                                        .size(48.dp)
                                        .clip(CircleShape)
                                        .background(PundarTheme.colors.surfaceTertiary)
                                ) {
                                    Icon(
                                        Icons.Filled.Remove,
                                        contentDescription = "Decrease people",
                                        tint = PundarTheme.colors.textPrimary
                                    )
                                }

                                OutlinedTextField(
                                    value = peopleCountInput,
                                    onValueChange = { input ->
                                        val digits = input.filter { it.isDigit() }.take(3)
                                        peopleCountInput = digits
                                    },
                                    label = { Text("Number of People") },
                                    singleLine = true,
                                    keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Number),
                                    modifier = Modifier.weight(1f),
                                    shape = RoundedCornerShape(12.dp),
                                    colors = OutlinedTextFieldDefaults.colors(
                                        focusedBorderColor = PundarTheme.colors.brandPrimary,
                                        focusedLabelColor = PundarTheme.colors.brandPrimary,
                                        focusedTextColor = PundarTheme.colors.textPrimary,
                                        unfocusedTextColor = PundarTheme.colors.textPrimary
                                    )
                                )

                                IconButton(
                                    onClick = {
                                        val current = peopleCountInput.toIntOrNull() ?: 1
                                        peopleCountInput = (current + 1).toString()
                                    },
                                    modifier = Modifier
                                        .size(48.dp)
                                        .clip(CircleShape)
                                        .background(PundarTheme.colors.brandPrimary.copy(alpha = 0.15f))
                                ) {
                                    Icon(
                                        Icons.Filled.Add,
                                        contentDescription = "Increase people",
                                        tint = PundarTheme.colors.brandPrimary
                                    )
                                }
                            }

                            // Quick select chips for number of people
                            Row(
                                modifier = Modifier.fillMaxWidth(),
                                horizontalArrangement = Arrangement.spacedBy(8.dp)
                            ) {
                                listOf("2", "3", "4", "5", "6", "8").forEach { qty ->
                                    val isSelected = peopleCountInput == qty
                                    OutlinedButton(
                                        onClick = { peopleCountInput = qty },
                                        modifier = Modifier.weight(1f),
                                        shape = RoundedCornerShape(10.dp),
                                        contentPadding = PaddingValues(vertical = 6.dp),
                                        border = BorderStroke(
                                            1.dp,
                                            if (isSelected) PundarTheme.colors.brandPrimary else PundarTheme.colors.borderPrimary
                                        ),
                                        colors = ButtonDefaults.outlinedButtonColors(
                                            containerColor = if (isSelected) PundarTheme.colors.brandPrimary.copy(alpha = 0.12f) else PundarTheme.colors.surfacePrimary
                                        )
                                    ) {
                                        Text(
                                            text = "${qty}p",
                                            fontSize = 12.sp,
                                            fontWeight = if (isSelected) FontWeight.Bold else FontWeight.Medium,
                                            color = if (isSelected) PundarTheme.colors.brandPrimary else PundarTheme.colors.textPrimary
                                        )
                                    }
                                }
                            }
                        }

                        // 6. Optional Payer Instructions / Notes
                        Text(
                            "6. Notes / Instructions for Payer",
                            style = MaterialTheme.typography.labelLarge,
                            fontWeight = FontWeight.SemiBold,
                            color = PundarTheme.colors.textPrimary
                        )
                        OutlinedTextField(
                            value = notesInput,
                            onValueChange = { notesInput = it },
                            label = { Text("Notes or Memo (Optional)") },
                            placeholder = { Text("e.g. Includes service charge, settle before 9 PM") },
                            leadingIcon = { Icon(Icons.Filled.Notes, contentDescription = null) },
                            singleLine = true,
                            modifier = Modifier.fillMaxWidth(),
                            shape = RoundedCornerShape(12.dp),
                            colors = OutlinedTextFieldDefaults.colors(
                                focusedBorderColor = PundarTheme.colors.brandPrimary,
                                focusedLabelColor = PundarTheme.colors.brandPrimary,
                                focusedTextColor = PundarTheme.colors.textPrimary,
                                unfocusedTextColor = PundarTheme.colors.textPrimary
                            )
                        )

                        // Live Split Calculation Preview
                        if (perPersonAmount != null && totalAmount != null && peopleCount != null) {
                            Surface(
                                shape = RoundedCornerShape(14.dp),
                                color = PundarTheme.colors.brandPrimary.copy(alpha = 0.08f),
                                border = BorderStroke(1.dp, PundarTheme.colors.brandPrimary.copy(alpha = 0.25f)),
                                modifier = Modifier.fillMaxWidth()
                            ) {
                                Column(
                                    modifier = Modifier.padding(14.dp),
                                    verticalArrangement = Arrangement.spacedBy(6.dp)
                                ) {
                                    Row(
                                        modifier = Modifier.fillMaxWidth(),
                                        horizontalArrangement = Arrangement.SpaceBetween
                                    ) {
                                        Text(
                                            "Category & Title:",
                                            style = MaterialTheme.typography.bodySmall,
                                            color = PundarTheme.colors.textSecondary
                                        )
                                        Text(
                                            "$selectedCategory • ${billTitleInput.ifBlank { "Untitled" }}",
                                            style = MaterialTheme.typography.bodySmall,
                                            fontWeight = FontWeight.Bold,
                                            color = PundarTheme.colors.textPrimary
                                        )
                                    }
                                    Row(
                                        modifier = Modifier.fillMaxWidth(),
                                        horizontalArrangement = Arrangement.SpaceBetween
                                    ) {
                                        Text(
                                            "Total Bill Amount:",
                                            style = MaterialTheme.typography.bodySmall,
                                            color = PundarTheme.colors.textSecondary
                                        )
                                        Text(
                                            "₱${String.format(Locale.US, "%,.2f", totalAmount)}",
                                            style = MaterialTheme.typography.bodySmall,
                                            fontWeight = FontWeight.Bold,
                                            color = PundarTheme.colors.textPrimary
                                        )
                                    }
                                    Row(
                                        modifier = Modifier.fillMaxWidth(),
                                        horizontalArrangement = Arrangement.SpaceBetween
                                    ) {
                                        Text(
                                            "People Joining the Bill:",
                                            style = MaterialTheme.typography.bodySmall,
                                            color = PundarTheme.colors.textSecondary
                                        )
                                        Text(
                                            "$peopleCount ${if (peopleCount == 1) "person" else "people"}",
                                            style = MaterialTheme.typography.bodySmall,
                                            fontWeight = FontWeight.Bold,
                                            color = PundarTheme.colors.textPrimary
                                        )
                                    }
                                    HorizontalDivider(color = PundarTheme.colors.borderPrimary)
                                    Row(
                                        modifier = Modifier.fillMaxWidth(),
                                        horizontalArrangement = Arrangement.SpaceBetween,
                                        verticalAlignment = Alignment.CenterVertically
                                    ) {
                                        Row(verticalAlignment = Alignment.CenterVertically) {
                                            Icon(
                                                Icons.Filled.Lock,
                                                contentDescription = null,
                                                tint = PundarTheme.colors.brandPrimary,
                                                modifier = Modifier.size(15.dp)
                                            )
                                            Spacer(Modifier.width(4.dp))
                                            Text(
                                                "Locked Share per Person:",
                                                style = MaterialTheme.typography.bodyMedium,
                                                fontWeight = FontWeight.Bold,
                                                color = PundarTheme.colors.textPrimary
                                            )
                                        }
                                        Text(
                                            "₱${String.format(Locale.US, "%,.2f", perPersonAmount)}",
                                            style = MaterialTheme.typography.titleMedium,
                                            fontWeight = FontWeight.ExtraBold,
                                            color = PundarTheme.colors.brandPrimary
                                        )
                                    }
                                    Text(
                                        "Anyone scanning this QR code will have their payment locked to ₱${String.format(Locale.US, "%,.2f", perPersonAmount)} and cannot modify the amount.",
                                        style = MaterialTheme.typography.labelSmall,
                                        color = PundarTheme.colors.textSecondary
                                    )
                                }
                            }
                        }

                        PundarPrimaryButton(
                            text = "Review & Generate QR Code",
                            enabled = true,
                            onClick = {
                                when {
                                    !isTitleValid -> {
                                        statusDialogState = Triple(
                                            "Missing Bill / Request Title",
                                            "Please enter a title or purpose (e.g. Team Dinner, Utility Split) before generating the QR code.",
                                            true
                                        )
                                    }
                                    totalAmount == null -> {
                                        statusDialogState = Triple(
                                            "Invalid Request Amount",
                                            "Please enter a valid total amount greater than ₱0.00 before generating the QR code.",
                                            true
                                        )
                                    }
                                    peopleCount == null -> {
                                        statusDialogState = Triple(
                                            "Invalid Participant Count",
                                            "Please specify at least 1 person for this payment request.",
                                            true
                                        )
                                    }
                                    else -> {
                                        showGenerateConfirmDialog = true
                                    }
                                }
                            }
                        )
                    }
                }
            } else {
                // ── STEP 2: GENERATED QR CODE SCREEN ──────────────────────────
                if (!user?.stellarPublicKey.isNullOrBlank()) {
                    SingleChoiceSegmentedButtonRow(modifier = Modifier.fillMaxWidth()) {
                        SegmentedButton(
                            selected = qrMode == 0,
                            onClick = { qrMode = 0 },
                            shape = SegmentedButtonDefaults.itemShape(index = 0, count = 2)
                        ) { Text("PUNDAR QR") }
                        SegmentedButton(
                            selected = qrMode == 1,
                            onClick = { qrMode = 1 },
                            shape = SegmentedButtonDefaults.itemShape(index = 1, count = 2)
                        ) { Text("Stellar QR") }
                    }
                }

                Card(
                    modifier = Modifier.fillMaxWidth(),
                    colors = CardDefaults.cardColors(containerColor = PundarTheme.colors.surfacePrimary),
                    shape = RoundedCornerShape(20.dp),
                    border = BorderStroke(1.dp, PundarTheme.colors.borderPrimary)
                ) {
                    Column(
                        modifier = Modifier.padding(24.dp).fillMaxWidth(),
                        horizontalAlignment = Alignment.CenterHorizontally
                    ) {
                        if (qrBitmap != null) {
                            Image(
                                bitmap = qrBitmap.asImageBitmap(),
                                contentDescription = "Receive money QR code",
                                modifier = Modifier.size(220.dp)
                            )
                        } else {
                            Box(
                                modifier = Modifier.size(220.dp),
                                contentAlignment = Alignment.Center
                            ) {
                                CircularProgressIndicator(color = PundarTheme.colors.brandPrimary)
                            }
                        }
                        Spacer(Modifier.height(12.dp))
                        Surface(
                            shape = RoundedCornerShape(10.dp),
                            color = PundarTheme.colors.brandPrimary.copy(alpha = 0.12f)
                        ) {
                            Row(
                                modifier = Modifier.padding(horizontal = 12.dp, vertical = 6.dp),
                                verticalAlignment = Alignment.CenterVertically
                            ) {
                                Icon(
                                    Icons.Filled.Lock,
                                    contentDescription = null,
                                    tint = PundarTheme.colors.brandPrimary,
                                    modifier = Modifier.size(15.dp)
                                )
                                Spacer(Modifier.width(6.dp))
                                Text(
                                    "Fixed Share: ₱${String.format(Locale.US, "%,.2f", perPersonAmount ?: 0.0)} / person (≈ ${String.format(Locale.US, "%,.2f", AppState.phpToXlm(perPersonAmount ?: 0.0))} XLM)",
                                    style = MaterialTheme.typography.bodyMedium,
                                    color = PundarTheme.colors.brandPrimary,
                                    fontWeight = FontWeight.ExtraBold
                                )
                            }
                        }
                        Spacer(Modifier.height(6.dp))
                        Text(
                            "Total Bill: ₱${String.format(Locale.US, "%,.2f", totalAmount ?: 0.0)} · Split among ${peopleCount ?: 1} ${if ((peopleCount ?: 1) == 1) "person" else "people"}",
                            style = MaterialTheme.typography.bodySmall,
                            color = PundarTheme.colors.textSecondary,
                            fontWeight = FontWeight.SemiBold,
                            textAlign = TextAlign.Center
                        )
                        Text(
                            "Bill: $effectiveBillTitle (Amount locked — payer cannot edit)",
                            style = MaterialTheme.typography.labelSmall,
                            color = PundarTheme.colors.textSecondary,
                            textAlign = TextAlign.Center
                        )
                        Spacer(Modifier.height(8.dp))
                        Text(
                            "Mobile: ${user?.phone ?: user?.id ?: ""}",
                            style = MaterialTheme.typography.labelMedium,
                            color = PundarTheme.colors.textPrimary
                        )
                        if (!user?.stellarPublicKey.isNullOrBlank()) {
                            Spacer(Modifier.height(4.dp))
                            val pk = user!!.stellarPublicKey!!
                            Text(
                                "Stellar: ${pk.take(8)}...${pk.takeLast(6)} (tap to copy)",
                                style = MaterialTheme.typography.labelSmall,
                                color = PundarTheme.colors.brandPrimary,
                                modifier = Modifier.clickable {
                                    val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
                                    clipboard.setPrimaryClip(ClipData.newPlainText("Stellar Public Key", pk))
                                    Toast.makeText(context, "Stellar address copied", Toast.LENGTH_SHORT).show()
                                }
                            )
                        }
                    }
                }

                PundarOutlinedButton(
                    text = "Edit Amount / People (${peopleCount ?: 1})",
                    onClick = { isQrGenerated = false },
                    modifier = Modifier.fillMaxWidth(),
                    icon = Icons.Filled.Edit
                )

                val copyAddressMode = qrMode == 1 && !user?.stellarPublicKey.isNullOrBlank()
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    PundarOutlinedButton(
                        text = if (copyAddressMode) "Copy Address" else "Copy ID",
                        onClick = {
                            val copyVal = if (copyAddressMode) {
                                user!!.stellarPublicKey!!
                            } else {
                                user?.id ?: return@PundarOutlinedButton
                            }
                            val label = if (copyAddressMode) "Stellar Address" else "User ID"
                            val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
                            clipboard.setPrimaryClip(ClipData.newPlainText(label, copyVal))
                            Toast.makeText(context, "$label copied", Toast.LENGTH_SHORT).show()
                        },
                        modifier = Modifier.weight(1f),
                        icon = Icons.Filled.ContentCopy
                    )
                    PundarOutlinedButton(
                        text = "Save",
                        onClick = {
                            val bmp = qrBitmap ?: return@PundarOutlinedButton
                            val fileName = "PUNDAR_QR_${user?.id ?: "wallet"}_${System.currentTimeMillis()}.png"
                            QrCodeGenerator.saveBitmapToGallery(context, bmp, fileName)
                                .onSuccess {
                                    statusDialogState = Triple(
                                        "QR Code Saved",
                                        "Your payment QR code has been saved to Pictures/PUNDAR in your gallery.",
                                        false
                                    )
                                }
                                .onFailure { e ->
                                    statusDialogState = Triple(
                                        "Save Failed",
                                        e.message ?: "Unable to save QR code to gallery.",
                                        true
                                    )
                                }
                        },
                        modifier = Modifier.weight(1f),
                        icon = Icons.Filled.Download
                    )
                    PundarOutlinedButton(
                        text = "Share",
                        onClick = {
                            val bmp = qrBitmap ?: return@PundarOutlinedButton
                            val shareAmtText = String.format(Locale.US, "%,.2f", perPersonAmount ?: 0.0)
                            val totalAmtText = String.format(Locale.US, "%,.2f", totalAmount ?: 0.0)
                            val pk = user?.stellarPublicKey?.takeIf { it.isNotBlank() }
                            val stellarText = if (pk != null) " Stellar: $pk" else ""
                            QrCodeGenerator.shareQrBitmap(
                                context = context,
                                bitmap = bmp,
                                shareText = "Join '$effectiveBillTitle' on PUNDAR! Total: ₱$totalAmtText (${peopleCount ?: 1} people) · Your locked share: ₱$shareAmtText. Account: ${user?.id ?: ""}.$stellarText".trimEnd('.'),
                                chooserTitle = "Share Receive QR"
                            )
                        },
                        modifier = Modifier.weight(1f),
                        icon = Icons.Filled.Share
                    )
                }

                PundarTextButton(
                    text = "Refresh QR",
                    onClick = {
                        refreshNonce++
                        Toast.makeText(context, "QR refreshed", Toast.LENGTH_SHORT).show()
                    },
                    icon = Icons.Filled.Refresh
                )

                Spacer(Modifier.height(4.dp))

                PundarPrimaryButton(
                    text = "Done",
                    onClick = { navController.navigateUp() }
                )
            }
        }
    }
